// Downsample array to reduce datapoints for faster rendering
// Keeps first/last points and samples evenly across the range
const API_BASE_URL = import.meta.env.VITE_API_BASE_URL;

const downsampleArray = (arr, maxPoints = 500) => {
  if (!arr || arr.length <= maxPoints) return arr;
  
  const sampled = [];
  const step = Math.ceil(arr.length / maxPoints);
  
  for (let i = 0; i < arr.length; i += step) {
    sampled.push(arr[i]);
  }
  
  // Ensure we have the last point
  if (sampled[sampled.length - 1] !== arr[arr.length - 1]) {
    sampled.push(arr[arr.length - 1]);
  }
  
  return sampled;
};

export const getMeterData = async ({ meterId, date }) => {
  const name = meterId?.trim();
  const dateValue = date?.trim();

  if (!name || !dateValue) {
    console.warn("getMeterData called with empty meterId or date", { meterId, date });
    return null;
  }

  try {
    const url = new URL(`${API_BASE_URL}/mfm/meterData`);
    url.searchParams.set("name", name);
    url.searchParams.set("date", dateValue);

    const response = await fetch(url.toString());
    if (!response.ok) {
      console.error("Meter data API returned error", response.status, response.statusText);
      return null;
    }

    const result = await response.json();

    if (!result.success || !result.data) {
      return null;
    }

    const rawNow = result.data.rawDataNow;
    const rawAvg = result.data.rawDataAvg;
    const rawCont = result.data.rawDataContinuous;

    // create datetime array if API doesn't provide one
    let date_time =
      rawCont.date_time ||
      Array.from(
        { length: rawCont.current_i1?.length || 0 },
        (_, i) => i
      );

    // Downsample all continuous readings for faster rendering
    const MAX_POINTS = 500;
    date_time = downsampleArray(date_time, MAX_POINTS);
    
    const voltage_v1 = downsampleArray(rawCont.phase_v1 || [], MAX_POINTS);
    const voltage_v2 = downsampleArray(rawCont.phase_v2 || [], MAX_POINTS);
    const voltage_v3 = downsampleArray(rawCont.phase_v3 || [], MAX_POINTS);
    
    const current_i1 = downsampleArray(rawCont.current_i1 || [], MAX_POINTS);
    const current_i2 = downsampleArray(rawCont.current_i2 || [], MAX_POINTS);
    const current_i3 = downsampleArray(rawCont.current_i3 || [], MAX_POINTS);
    
    const active_power = downsampleArray(rawCont.KWh || [], MAX_POINTS);
    const kw_demand = downsampleArray(rawCont.KVAh || [], MAX_POINTS);
    
    const frequency = downsampleArray(rawCont.freq || [], MAX_POINTS);
    const power_factor = downsampleArray(rawCont.pf || [], MAX_POINTS);
    
    const apparent_power = downsampleArray(rawCont.KVAh || [], MAX_POINTS);
    const reactive_power = downsampleArray(rawCont.KVARh || [], MAX_POINTS);
    
    const active_energy = downsampleArray(rawCont.KWh || [], MAX_POINTS);

    return {
      status: true,

      meter_id: meterId,
      panel_id: "MFM PANEL",
      location: meterId,
      date: date,

      latest_reading: {
        voltage_v1: rawNow.phase_v1,
        voltage_v2: rawNow.phase_v2,
        voltage_v3: rawNow.phase_v3,
        line_v1: rawNow.line_v1,
        line_v2: rawNow.line_v2,
        line_v3: rawNow.line_v3,

        current_i1: rawNow.current_i1,
        current_i2: rawNow.current_i2,
        current_i3: rawNow.current_i3,

        active_power: rawNow.KWh,
        kw_demand: rawNow.KVAh,

        frequency: rawNow.freq,
        power_factor: rawNow.pf,

        apparent_power: rawNow.KVAh,
        reactive_power: rawNow.KVARh,

        thd_v: 0,
        thd_i: 0,

        active_energy: rawNow.KWh,
      },

      avg_reading: {
        voltage_v1: rawAvg.avg_phase_v1,
        voltage_v2: rawAvg.avg_phase_v2,
        voltage_v3: rawAvg.avg_phase_v3,
        line_v1: rawAvg.avg_line_v1 || rawAvg.line_vtg_avg,
        line_v2: rawAvg.avg_line_v2 || rawAvg.line_vtg_avg,
        line_v3: rawAvg.avg_line_v3 || rawAvg.line_vtg_avg,

        current_i1: rawAvg.avg_current_i1,
        current_i2: rawAvg.avg_current_i2,
        current_i3: rawAvg.avg_current_i3,

        active_power: rawAvg.avg_KWh,
        kw_demand: rawAvg.avg_KVAh,

        frequency: rawAvg.avg_freq,
        power_factor: rawAvg.avg_pf,

        apparent_power: rawAvg.avg_KVAh,
        reactive_power: rawAvg.avg_KVARh,

        thd_v: 0,
        thd_i: 0,

        active_energy: rawAvg.avg_KWh,
      },

      continues_readings: {
        date_time,
        voltage_v1,
        voltage_v2,
        voltage_v3,
        current_i1,
        current_i2,
        current_i3,
        active_power,
        kw_demand,
        frequency,
        power_factor,
        apparent_power,
        reactive_power,
        thd_v: [],
        thd_i: [],
        active_energy,
      },
    };
  } catch (error) {
    console.error("API Fetch Error:", error);
    return null;
  }
};







